/**
 * Minimal built-in i18n: English + German + French + Spanish.
 * English is the key language; missing keys fall back to English.
 * Filter/sort/repeat/sound ids stay English internally; only labels translate.
 */
object Lang {
    var code: String = "en"

    private fun c(): String {
        val l = code.lowercase()
        return when {
            l.startsWith("de") -> "de"
            l.startsWith("fr") -> "fr"
            l.startsWith("es") -> "es"
            else -> "en"
        }
    }

    fun t(key: String): String {
        val l = c()
        if (l == "en") return EN[key] ?: key
        return when (l) {
            "de" -> DE[key] ?: EN[key] ?: key
            "fr" -> FR[key] ?: EN[key] ?: key
            else -> ES[key] ?: EN[key] ?: key
        }
    }

    fun filterLabel(id: String): String = when (id) {
        "All" -> t("f_All")
        "Today" -> t("f_Today")
        "Next 7 days" -> t("f_Next7")
        "Featured" -> t("f_Featured")
        "With secret" -> t("f_Secret")
        "Past" -> t("f_Past")
        "To partner" -> t("f_Partner")
        else -> id
    }

    fun sortLabel(id: String): String = when (id) {
        "Happening next" -> t("s_Next")
        "Name A–Z" -> t("s_AZ")
        "Biggest countdown" -> t("s_Big")
        "Newest first" -> t("s_New")
        else -> id
    }

    fun repeatDisplay(en: String): String = when (en) {
        "One-time" -> t("r_Once")
        "Yearly" -> t("r_Yearly")
        "Monthly" -> t("r_Monthly")
        "Weekly" -> t("r_Weekly")
        else -> en
